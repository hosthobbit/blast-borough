import { launch, watchConsole, sleep } from "./browser.mjs";
const url = process.argv[2] || "http://localhost:5173/";
const out = process.argv[3] || "e2e/out";
const browser = await launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
const errors = watchConsole(page, "smoke");
await page.goto(url);
await page.waitForFunction(() => window.__bb && window.__bb.screen() === "title", null, { timeout: 30000 });
await sleep(2500);
await page.screenshot({ path: `${out}/01_title.png` });
await page.click("text=Play Solo");
await page.click("[data-start]");
await sleep(5000);
await page.screenshot({ path: `${out}/02_solo.png` });
await page.keyboard.down("KeyD"); await sleep(400); await page.keyboard.up("KeyD");
await page.keyboard.press("Space");
await page.keyboard.down("KeyA"); await sleep(500); await page.keyboard.up("KeyA");
await page.keyboard.down("KeyS"); await sleep(600); await page.keyboard.up("KeyS");
await sleep(900);
await page.screenshot({ path: `${out}/03_bomb.png` });
console.log("state", JSON.stringify(await page.evaluate(() => { const s = window.__bb.state(); return { tick: s.tick, phase: s.phase, alive: s.players.map((p) => p.alive) }; })));
console.log("errors", errors.length, errors.slice(0, 5));
await browser.close();
